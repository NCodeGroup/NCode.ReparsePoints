<#
.SYNOPSIS
    Fail when a commit in a range is attributed to an AI agent.

.DESCRIPTION
    Inspects every commit in Base..Head (merge commits included) and fails when the author or the committer is an AI
    agent account, or when the commit message carries agent attribution.

    An AI agent account is an AI agent's app or bot account, such as copilot-swe-agent[bot], claude[bot],
    chatgpt-codex-connector[bot], cursor[bot], devin-ai-integration[bot] or google-labs-jules[bot], by its name or its
    users.noreply.github.com address, an address only an agent uses, such as noreply@anthropic.com (any @anthropic.com
    address), noreply@openai.com, cursoragent@cursor.com or aider@aider.chat, or a name aider marks with " (aider)".
    Agent attribution is a Co-authored-by line that names an AI agent or model or uses such an address, whichever agent
    it is (Copilot, Claude, Codex, Cursor, Devin, Gemini, Grok, GitLab Duo, aider, a local model or any other), an agent
    session trailer (Claude-Session, Agent-Logs-Url, Amp-Thread-ID), a Made-with, Assisted-by or Generated-by trailer
    that names an AI tool, a line that starts, after any leading symbols or underscores, with words such as
    "Generated with", "Generated by" or "Created by" and then an AI tool, such as the footer a Claude Code cloud session
    appends, or a line that holds only a link to an agent's session or task, such as claude.ai/code/session_ or
    chatgpt.com/codex/tasks/. Matching is case-insensitive, and .githooks/commit-msg uses the same patterns.
    A name an agent shares with people, such as Claude, Devin or Jules, counts only with an agent's address or a
    model's name, so a person's co-author trailer passes. Dependabot, Renovate, github-actions and the
    GitHub <noreply@github.com> committer are not AI agents and pass. Git's output is read as UTF-8 whatever the
    console's code page.

    When Base is empty, is all zeros, or is not a commit in the clone (a new branch, or a force-push), only Head is
    checked, so the check never fails for a reason other than attribution.

    On failure each finding is written as "<short sha> <subject>: <finding>", followed by the remedy: rewrite the
    commits with git rebase <base> --exec "git commit --amend --no-edit --reset-author", then git push
    --force-with-lease. For a message with attribution the remedy adds -c core.hooksPath=.githooks after git, so the
    project's commit-msg hook strips those lines, which --amend --no-edit alone keeps, and leaves out --reset-author
    when no agent account authored or committed a commit. When GITHUB_ACTIONS is true each finding is also written as
    a workflow error annotation, with %, CR and LF escaped.

    When PullRequestTitle or PullRequestBody is given, the pull request's title and description (on GitLab, when
    GITLAB_CI is true, the merge request's) are checked line by line for the same attribution lines, because a squash
    merge can make them the message of the commit on the default branch. The remedy for such a finding is to edit the
    title or description.

    This file comes from the project template. Template updates replace it, so a local edit is lost.

.PARAMETER Base
    The revision that excludes the commits already accepted. Commits in Base..Head are checked. May be empty.

.PARAMETER Head
    The revision whose history is checked. Defaults to HEAD.

.PARAMETER Root
    The project root. Defaults to the parent of the .template directory.

.PARAMETER PullRequestTitle
    The title of the pull request (merge request). Pass it through an environment variable, never interpolated into a
    command. When it and PullRequestBody are both empty, as on a push, nothing extra is checked.

.PARAMETER PullRequestBody
    The description of the pull request (merge request). Pass it through an environment variable, never interpolated
    into a command. When it and PullRequestTitle are both empty, as on a push, nothing extra is checked.

.EXAMPLE
    .\.template\Test-CommitAttribution.ps1 -Base origin/main

.EXAMPLE
    .\.template\Test-CommitAttribution.ps1 -Base origin/main -PullRequestTitle $env:PR_TITLE -PullRequestBody $env:PR_BODY

.EXAMPLE
    .\.template\Test-CommitAttribution.ps1 -Base origin/main~20 -Head origin/main
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)]
    [AllowEmptyString()]
    [string]$Base,
    [string]$Head = 'HEAD',
    [string]$Root = (Split-Path -Parent $PSScriptRoot),
    [string]$PullRequestTitle = '',
    [string]$PullRequestBody = ''
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$Root = [IO.Path]::GetFullPath($Root)
$outputEncoding = [Console]::OutputEncoding
# The same patterns as .githooks/commit-msg, character for character, so the hook strips every line the check fails.
# They use only regex syntax .NET and POSIX ERE share; -match is case-insensitive, as grep -i is in the hook.
$agentBot = '(claude|copilot-swe-agent|anthropic-code-agent|chatgpt-codex-connector|cursor|devin-ai-integration|google-labs-jules|gemini-code-assist|grok-by-xai|amazon-q-developer|kiro-agent|jetbrains-junie|windsurf-bot|factory-droid|kiloconnect|kilo-code-bot|augmentcode|opencode-agent)\[bot\]'
$agentLogin = "(copilot|claude|gemini-cli|$agentBot)"
$agentAddress = '([^>]*@anthropic\.com|(noreply|codex)@openai\.com|(cursoragent|noreply)@cursor\.com|aider@aider\.chat|(amp|noreply)@ampcode\.com|noreply@continue\.dev|crush@charm\.land|qwen-coder@alibabacloud\.com|openhands@all-hands\.dev|(agent|oz-agent)@warp\.dev|(noreply|agent)@augmentcode\.com|noreply@kiro\.dev|noreply@kilo\.ai|agent@kilocode\.ai|noreply@cline\.bot|noreply@codeium\.com|cascade@windsurf\.ai|noreply@tabnine\.com|junie@(jetbrains\.com|air\.dev)|copilot@github\.com|noreply@x\.ai|noreply@pi\.dev|noreply@cognition\.ai|noreply@google\.com|noreply@antigravity\.google|codewhisperer@amazon\.com|gitlab-duo@[^>]*|ai@local)'
$accountName = "^(copilot-swe-agent|(github )?copilot( app)?|$agentBot|cursor[ -]agent|devin ai|openhands|.+ \(aider\))`$"
$accountEmail = "(^|[+])$agentLogin@users\.noreply\.github\.com`$|^$agentAddress`$"
$attributionLines = @(
    "^ *co-authored-by:.*<(([^>]*[+])?${agentLogin}@users\.noreply\.github\.com|${agentAddress})>",
    '^ *co-authored-by: *(github +)?(copilot[^<]*|codex|chatgpt|openhands|tabnine( cli)?|windsurf( cascade)?|codeium|aider( \([^)]*\))?|claude (code|opus|sonnet|haiku)[^<]*|grok [0-9][^<]*|gpt[- ]?[0-9][^<]*|cursor agent|devin ai|[^<]* via cursor) *<',
    '^ *(claude-session|agent-logs-url|amp-thread-id):',
    '^ *(made-with|assisted-by|generated-by): *(claude (code|opus|sonnet|haiku)|(claude|devin|jules|kiro|junie|cline|amp|kilo|augment):|(anthropic|(github +)?copilot|codex|chatgpt|openai|gpt-?[0-9][a-z0-9.]*|cursor|crush|gemini|grok|aider|windsurf|codeium|tabnine|qwen[0-9.]*|openhands|opencode|kilo code|augment code|amazon q|codewhisperer|gitlab duo|ollama|deepseek)([^a-zA-Z0-9]|$))',
    '^[^a-zA-Z0-9]*((this )?(pr|pull request|mr|merge request|commit|change|issue|comment) (was )?)?(generated|created|written|made|co-authored|authored|built)( automatically)? +(with|by|using|via) +(\[(claude|devin|jules|kiro|junie|continue|amp)\]|\[?(claude (code|opus|sonnet|haiku)|claude\.ai|anthropic|(github +)?copilot|codex|chatgpt|openai|gpt-?[0-9][a-z0-9.]*|cursor|gemini|antigravity|grok|aider|crush|codeium|windsurf|cline|tabnine|qwen[0-9.]*|deepseek|openhands|opencode|amazon q|codewhisperer|(amazon )?bedrock|gitlab duo|kilo code|ollama|lm studio|jules for task|(an )?ai( agent| model| tool| assistant)?)([^a-zA-Z0-9]|$))',
    '^[^a-zA-Z0-9]*([a-z][a-z ]{0,39}: *)?(https?://)?(claude\.ai/code/session_|chatgpt\.com/codex/tasks/|chatgpt\.com/s/cd_|cursor\.com/agents/|cursor\.com/background-agent|app\.devin\.ai/sessions/|jules\.google\.com/task/|ampcode\.com/threads/|app\.all-hands\.dev/conversations/|opencode\.ai/s/)[^ ]* *$'
)
$isGitLab = $env:GITLAB_CI -eq 'true'
$requestName = if ($isGitLab) { 'merge request' } else { 'pull request' }
$requestLabel = if ($isGitLab) { 'Merge request' } else { 'Pull request' }
$checkRequest = -not ([string]::IsNullOrWhiteSpace($PullRequestTitle) -and [string]::IsNullOrWhiteSpace($PullRequestBody))

function Test-AgentAccount([string]$Name, [string]$Email) {
    return ($Name -match $accountName) -or ($Email -match $accountEmail)
}

try {
    # Read Git's output as UTF-8, so the emoji before "Generated with" stays a symbol whatever the console's code page.
    try { [Console]::OutputEncoding = [Text.UTF8Encoding]::new($false) } catch { Write-Verbose "Couldn't set the console's output encoding: $_" }

    $headCommit = & git -C $Root rev-parse --verify "$Head^{commit}" 2>$null
    if ($LASTEXITCODE -ne 0) {
        throw "Head '$Head' is not a commit in $Root."
    }

    $baseEmpty = [string]::IsNullOrWhiteSpace($Base)
    $baseKnown = $false
    if (-not $baseEmpty -and $Base -notmatch '^0+$') {
        $null = & git -C $Root rev-parse --verify --quiet "$Base^{commit}" 2>$null
        $baseKnown = $LASTEXITCODE -eq 0
    }
    $remedyBase = if ($baseKnown) { $Base } else { '<base>' }

    if ($baseKnown) {
        $commits = [string[]]@(& git -C $Root rev-list "$Base..$Head")
        if ($LASTEXITCODE -ne 0) {
            throw "git rev-list $Base..$Head failed."
        }
    }
    else {
        if ($baseEmpty) {
            Write-Output "Commit attribution: no base given; checking $Head only."
        }
        else {
            Write-Output "Commit attribution: base $Base is not in this clone; checking $Head only."
        }
        $commits = [string[]]@($headCommit)
    }

    $findings = [System.Collections.Generic.List[string]]::new()
    $accountFound = $false
    $messageFound = $false
    foreach ($commit in $commits) {
        $fields = (@(& git -C $Root log -1 '--format=%h%x00%s%x00%an%x00%ae%x00%cn%x00%ce' $commit) -join "`n") -split "`0"
        if ($LASTEXITCODE -ne 0 -or $fields.Count -ne 6) {
            throw "git log failed for commit $commit."
        }
        $message = [string[]]@(& git -C $Root log -1 '--format=%B' $commit)
        if ($LASTEXITCODE -ne 0) {
            throw "git log failed for commit $commit."
        }

        $prefix = "$($fields[0]) $($fields[1])"
        if (Test-AgentAccount $fields[2] $fields[3]) {
            $findings.Add("${prefix}: author $($fields[2]) $($fields[3]) is an AI agent account")
            $accountFound = $true
        }
        if (Test-AgentAccount $fields[4] $fields[5]) {
            $findings.Add("${prefix}: committer $($fields[4]) $($fields[5]) is an AI agent account")
            $accountFound = $true
        }
        foreach ($line in $message) {
            foreach ($pattern in $attributionLines) {
                if ($line -match $pattern) {
                    $findings.Add("${prefix}: message has agent attribution: $(($line -replace '[\x00-\x1F\x7F]', ' ').Trim())")
                    $messageFound = $true
                    break
                }
            }
        }
    }

    $requestFindings = [System.Collections.Generic.List[string]]::new()
    if ($checkRequest) {
        $requestText = [ordered]@{ title = $PullRequestTitle; description = $PullRequestBody }
        foreach ($entry in $requestText.GetEnumerator()) {
            foreach ($line in ($entry.Value -split '\r?\n')) {
                foreach ($pattern in $attributionLines) {
                    if ($line -match $pattern) {
                        $requestFindings.Add("$requestLabel $($entry.Key): has agent attribution: $(($line -replace '[\x00-\x1F\x7F]', ' ').Trim())")
                        break
                    }
                }
            }
        }
    }

    if ($findings.Count + $requestFindings.Count -eq 0) {
        if ($checkRequest) {
            Write-Output "Commit attribution: the $requestName's title and description have no agent attribution."
        }
        Write-Output "Commit attribution: $($commits.Count) commit(s) checked; none is attributed to an AI agent."
        exit 0
    }

    foreach ($finding in $findings) {
        Write-Output $finding
    }
    foreach ($finding in $requestFindings) {
        Write-Output $finding
    }
    if ($findings.Count) {
        # --amend --no-edit keeps a message as it is, so for a message with attribution the remedy runs the project's
        # commit-msg hook on it, which strips those lines, whatever hooks path the clone has.
        $amend = if ($messageFound) { 'git -c core.hooksPath=.githooks commit --amend --no-edit' } else { 'git commit --amend --no-edit' }
        if ($accountFound) { $amend += ' --reset-author' }
        $remedyStart = if ($accountFound) { 'Re-author these commits before merging' } else { 'Rewrite these commits before merging' }
        $hookNote = if ($messageFound) { ', which runs .githooks/commit-msg to strip the attribution lines from each message' } else { '' }
        Write-Output "${remedyStart}: git rebase $remedyBase --exec ""$amend""$hookNote, then git push --force-with-lease."
    }
    if ($requestFindings.Count) {
        $requestRemedy = if ($isGitLab) { "Then run the merge request's pipeline again." } else { 'Editing the pull request runs this check again.' }
        Write-Output "Edit the $requestName's title and description to remove these lines: a rebase doesn't change them, and a squash merge would copy them into the commit on the default branch. $requestRemedy"
    }
    if ($env:GITHUB_ACTIONS -eq 'true') {
        foreach ($finding in @($findings) + @($requestFindings)) {
            $message = $finding.Replace('%', '%25').Replace("`r", '%0D').Replace("`n", '%0A')
            Write-Output "::error title=Commit attribution::$message"
        }
    }
    exit 1
}
finally {
    try { [Console]::OutputEncoding = $outputEncoding } catch { Write-Verbose "Couldn't restore the console's output encoding: $_" }
}
